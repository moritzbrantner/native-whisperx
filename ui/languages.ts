export const translationLanguages = ["en", "de", "fr", "es", "it", "pt", "nl", "pl"] as const;
const names = new Intl.DisplayNames(["en"], { type: "language" });
export function languageLabel(code: string): string {
  try {
    return `${names.of(code) ?? code} · ${code}`;
  } catch {
    return code;
  }
}
export function languageOptions(codes: readonly string[]) {
  return codes
    .map((code) => ({ code, label: languageLabel(code) }))
    .sort((a, b) => a.label.localeCompare(b.label, "en"));
}
